#!/usr/bin/env python3
"""
Build dctitleid.txt, the catalog apollo-ps3 uses to find the patch for a
Dreamcast VMU save.

VMU saves carry no title ID: a game names its files itself (SONICADV_002,
SONICADV_501, ...), often differently per region (MVLVS.C2_SYS in Japan,
MVLVSCP2_SYS in the US). So each DC patch lists, in its header, the file
names it handles, one wildcard pattern per line:

    ; MVLVSCP2_SYS
    ; Marvel vs. Capcom 2: New Age of Heroes
    ; DC: MVLVSCP2_SYS
    ; DC: MVLVS.C2_SYS

and this script collects them into one tab-separated file:

    PATTERN <TAB> PATCH_ID <TAB> TITLE

The app takes the first pattern that matches a save's name (case-insensitive,
'*' and '?' wildcards), so lines are sorted most specific first: exact names,
then patterns with more literal characters. A patch without "; DC:" lines is
listed under its own file name, so an exact-name patch is never shadowed by a
broader pattern from another one.

Usage: build-dc-catalog.py <DC patches dir> <output file>
"""

import os
import re
import sys

DC_LINE = re.compile(r"^;\s*DC:\s*(.*)$", re.IGNORECASE)
VMU_NAME_MAX = 12


def decode(raw):
    # Some patches are Windows-1252, not UTF-8
    for encoding in ("utf-8", "cp1252"):
        try:
            return raw.decode(encoding)
        except UnicodeDecodeError:
            continue
    return raw.decode("latin-1")


def read_header(path):
    """The patch's "; DC:" patterns and its title (second line, by convention)."""
    with open(path, "rb") as fh:
        lines = [decode(raw).strip() for raw in fh.read().split(b"\n")]

    title = lines[1].lstrip(";").strip() if len(lines) > 1 else ""
    patterns = []

    # Only the leading comment block is the header
    for line in lines:
        if line and not line.startswith(";"):
            break
        match = DC_LINE.match(line)
        if match:
            patterns.extend(match.group(1).split())

    return patterns, title


def specificity(pattern):
    literal = len(pattern.replace("*", "").replace("?", ""))
    wild = any(c in pattern for c in "*?")
    return (wild, -literal, pattern.upper())


def main(src, out):
    entries = []
    owner = {}
    errors = 0

    for entry in sorted(os.listdir(src)):
        if not entry.endswith(".savepatch"):
            continue

        patch_id = entry[: -len(".savepatch")]
        patterns, title = read_header(os.path.join(src, entry))
        if not patterns:
            patterns = [patch_id]

        for pattern in patterns:
            if "\t" in pattern or len(pattern.replace("*", "")) > VMU_NAME_MAX:
                print(f"error: {entry}: '{pattern}' can't match a VMU file name", file=sys.stderr)
                errors += 1
                continue

            key = pattern.upper()
            if key in owner and owner[key] != patch_id:
                print(f"error: {entry}: '{pattern}' is already listed by {owner[key]}.savepatch", file=sys.stderr)
                errors += 1
                continue

            owner[key] = patch_id
            entries.append((pattern, patch_id, title or patch_id))

    if errors:
        return 1

    entries.sort(key=lambda e: specificity(e[0]))
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# Dreamcast VMU save name -> patch catalog, generated by tools/build-dc-catalog.py\n")
        fh.write("# PATTERN\tPATCH_ID\tTITLE (first match wins)\n")
        for pattern, patch_id, title in entries:
            fh.write(f"{pattern}\t{patch_id}\t{title}\n")

    print(f"{len(entries)} patterns from {len(set(e[1] for e in entries))} patches -> {out}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1], sys.argv[2]))
